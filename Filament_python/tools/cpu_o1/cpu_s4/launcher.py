"""Scoped S4 allocation launcher; it never submits to Slurm."""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import sys

SCHEMA = "filament.cpu_s4.real8_authorization.v1"
RESOURCES = {"nodes": 1, "physical_cpus": 96, "gpus": 0,
             "memory_GiB": 320, "seconds": 7200, "max_submissions": 1}
RUNTIME_CHECKS = frozenset({
    "slurm_job_resources", "physical_cpu_affinity", "effective_cgroup_memory",
    "supervisor_signal_cleanup", "parent_loss_cleanup", "fourteen_input_hashes",
    "output_inventory_21_and_negative_cases", "storage_quota_bytes_and_inodes",
    "post_test_frozen_storage_admission", "runtime_test_storage_reserve",
})
# Runtime evidence is generated by the launcher in the same allocation.
RUNTIME_GATE_PRODUCER_AVAILABLE = True


def _read_strict(path: Path) -> dict:
    def reject(token):
        raise ValueError(f"nonstandard JSON number: {token}")
    value = json.loads(path.read_text(encoding="utf-8"), parse_constant=reject)
    if not isinstance(value, dict):
        raise ValueError(f"expected JSON object: {path}")
    return value


def validate_scoped_authorization(*, run_config_path: Path,
                                  approval_path: Path,
                                  output_root: Path,
                                  authorized_run_root: Path | None = None,
                                  require_launcher_marker: bool = True,
                                  check_runtime: bool = True) -> dict:
    """Validate one task-bound authorization and same-allocation Linux gate."""
    config_path = Path(run_config_path).resolve(strict=True)
    approval_path = Path(approval_path).resolve(strict=True)
    config = _read_strict(config_path)
    approval = _read_strict(approval_path)
    run_id = os.environ.get("HPC_AUTHORIZED_RUN_ID")
    if (approval.get("schema") != SCHEMA or approval.get("authorized") is not True
            or not isinstance(run_id, str) or not run_id
            or approval.get("run_id") != run_id):
        raise RuntimeError("BLOCKED_REAL_EXECUTION_REQUIRES_TASK_BOUND_AUTHORIZATION")
    if require_launcher_marker and os.environ.get(
            "CPU_S4_SCOPED_LAUNCHER_RUN_ID") != run_id:
        raise RuntimeError("BLOCKED_REAL_EXECUTION_REQUIRES_SCOPED_LAUNCHER")
    if approval.get("resources") != RESOURCES:
        raise RuntimeError("BLOCKED_AUTHORIZATION_RESOURCE_MISMATCH")
    if approval.get("run_config_sha256") is None:
        raise RuntimeError("BLOCKED_AUTHORIZATION_RUN_CONFIG_HASH_MISSING")

    bench = Path(config["bench_root"]).resolve(strict=True)
    if str(bench) not in sys.path:
        sys.path.insert(0, str(bench))
    from tools.hpc_ops import provenance_v2 as pv
    if pv.raw_sha256_file(config_path) != approval["run_config_sha256"]:
        raise RuntimeError("BLOCKED_AUTHORIZATION_RUN_CONFIG_HASH_MISMATCH")
    actual_root = Path(authorized_run_root or output_root).resolve(strict=False)
    if Path(approval.get("run_root", "")).resolve(strict=False) != actual_root:
        raise RuntimeError("BLOCKED_AUTHORIZATION_RUN_ROOT_MISMATCH")
    for key in ("provenance", "adapter_provenance", "expected_inputs",
                "expected_source_binding"):
        if pv.raw_sha256_file(Path(config[key])) != approval.get(key + "_sha256"):
            raise RuntimeError("BLOCKED_AUTHORIZATION_SOURCE_BINDING_MISMATCH:" + key)

    adapter = Path(config["adapter_root"]).resolve(strict=True)
    if Path(__file__).resolve() != adapter / 'Filament_python/tools/cpu_o1/cpu_s4/launcher.py':
        raise RuntimeError('BLOCKED_EXECUTING_LAUNCHER_IDENTITY_MISMATCH')
    adapter_git_dir_value = config.get("adapter_git_dir")
    if not isinstance(adapter_git_dir_value, str) or not adapter_git_dir_value:
        raise RuntimeError("BLOCKED_ADAPTER_GIT_DIR_MISSING_FROM_RUN_CONFIG")
    adapter_python = str(adapter / "Filament_python")
    sys.path[:] = [entry for entry in sys.path if entry != adapter_python]
    sys.path.insert(0, adapter_python)
    from tools.cpu_o1.cpu_s4 import admission
    expected_admission = adapter / 'Filament_python/tools/cpu_o1/cpu_s4/admission.py'
    if Path(admission.__file__).resolve() != expected_admission.resolve():
        raise RuntimeError("BLOCKED_IMPORTED_ADMISSION_IS_NOT_FROM_ADAPTER")
    records = admission._validate_adapter_raw_manifest(
        adapter, Path(config["adapter_provenance"]), pv)
    overlay = admission._bind_s4_overlay_inventory(adapter, records, pv)
    if (overlay.get("status") != "PASS"
            or overlay.get("inventory_sha256") != approval.get("s4_overlay_inventory_sha256")):
        raise RuntimeError("BLOCKED_AUTHORIZATION_S4_OVERLAY_MISMATCH")
    adapter_git_context = admission.validate_adapter_git_context(
        adapter, Path(adapter_git_dir_value))

    job_id = os.environ.get("SLURM_JOB_ID")
    if not job_id:
        raise RuntimeError("BLOCKED_REAL_EXECUTION_REQUIRES_LIVE_SLURM_ALLOCATION")
    bound = {"run_id":run_id,"job_id":job_id,"config":config,"approval":approval,
             "overlay_inventory":overlay,
             "adapter_git_context":adapter_git_context}
    if not check_runtime:
        return bound
    if not RUNTIME_GATE_PRODUCER_AVAILABLE:
        raise RuntimeError("BLOCKED_RUNTIME_GATE_PRODUCER_NOT_IMPLEMENTED")
    runtime_path = Path(config.get("runtime_gate_receipt", "")).resolve(strict=True)
    runtime_gate = _read_strict(runtime_path)
    checks = runtime_gate.get("checks")
    if (runtime_gate.get("schema") != "filament.cpu_s4.linux_runtime_gate.v1"
            or runtime_gate.get("status") != "S4_1_LINUX_RUNTIME_GATE_PASS"
            or runtime_gate.get("run_id") != run_id
            or runtime_gate.get("job_id") != job_id
            or runtime_gate.get("resources") != RESOURCES
            or not isinstance(checks, dict)
            or not RUNTIME_CHECKS.issubset(checks)
            or any(checks.get(name) != "PASS" for name in RUNTIME_CHECKS)):
        raise RuntimeError("BLOCKED_RUNTIME_GATE_RECEIPT_INCOMPLETE_OR_NOT_BOUND")
    expected_bindings = {
        "authorization_sha256": pv.raw_sha256_file(approval_path),
        "run_config_sha256": approval["run_config_sha256"],
        "adapter_overlay_inventory_sha256": overlay["inventory_sha256"],
        "source_provenance_sha256": approval["provenance_sha256"],
        "adapter_provenance_sha256": approval["adapter_provenance_sha256"],
        "expected_inputs_sha256": approval["expected_inputs_sha256"],
        "expected_source_binding_sha256": approval["expected_source_binding_sha256"],
    }
    if any(runtime_gate.get(key) != value for key, value in expected_bindings.items()):
        raise RuntimeError("BLOCKED_RUNTIME_GATE_SOURCE_BINDING_MISMATCH")
    evidence = runtime_gate.get("evidence", [])
    required = {"scheduler_job.json", "allocation.json", "cgroup.json", "input_admission.json", "quota_raw.json",
                "storage_budget.json", "tests.json", "tests.xml", "tests.log", "allocation_probe/receipt.json",
                "post_test_storage.json", "post_test_storage_growth.json", "runtime_test_inventory.json"}
    if not required.issubset({row.get("path") for row in evidence}):
        raise RuntimeError("BLOCKED_RUNTIME_GATE_EVIDENCE_MISSING")
    for row in evidence:
        path = (runtime_path.parent / row["path"]).resolve(strict=True)
        if not path.is_relative_to(runtime_path.parent) or pv.raw_sha256_file(path) != row.get("sha256"):
            raise RuntimeError("BLOCKED_RUNTIME_GATE_EVIDENCE_HASH")
    from tools.cpu_o1.cpu_s4.runtime_gate import validate_junit
    validate_junit(runtime_path.parent / "tests.xml")
    return {"run_id": run_id, "job_id": job_id, "config": config,
            "approval": approval, "runtime_gate": runtime_gate,
            "overlay_inventory": overlay,
            "adapter_git_context": adapter_git_context}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run-config", type=Path, required=True)
    parser.add_argument("--approval", type=Path, required=True)
    parser.add_argument("--output-root", type=Path, required=True)
    args = parser.parse_args(argv)
    # All checks precede creation of the one-run lock. No scheduler command is
    # present here; Slurm submission stays under the independently reviewed batch.
    try:
        bound = validate_scoped_authorization(
            run_config_path=args.run_config, approval_path=args.approval,
            output_root=args.output_root, authorized_run_root=args.output_root,
            require_launcher_marker=False, check_runtime=False)
        if args.output_root.exists():
            raise FileExistsError(args.output_root)
        args.output_root.parent.mkdir(parents=True, exist_ok=True)
        lock = args.output_root.parent / (args.output_root.name + ".S4_ONCE.lock")
        with lock.open("x", encoding="utf-8") as stream:
            stream.write(bound["run_id"] + "\n" + bound["job_id"] + "\n")
            stream.flush()
            os.fsync(stream.fileno())
        from tools.cpu_o1.cpu_s4 import runtime_gate
        runtime_gate.run(bound, approval_path=args.approval,
                         config_path=args.run_config, output_root=args.output_root)
        os.environ["CPU_S4_SCOPED_LAUNCHER_RUN_ID"] = bound["run_id"]
        validate_scoped_authorization(run_config_path=args.run_config,
            approval_path=args.approval,output_root=args.output_root)
        from tools.cpu_o1.cpu_s4 import supervisor
        return int(supervisor.main([
            "--supervise-pair", "--output-root", str(args.output_root),
            "--run-config", str(args.run_config), "--approval", str(args.approval),
            "--authorized-run-root", str(args.output_root),
        ]))
    except BaseException as exc:
        print(json.dumps({"status": "BLOCKED", "error":
            f"{type(exc).__name__}: {exc}", "HPC_SUBMITTED": False},
            ensure_ascii=False, allow_nan=False), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
